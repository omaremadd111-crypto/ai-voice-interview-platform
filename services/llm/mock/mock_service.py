# Broader than the engine's own regex fast path on purpose: Mock Mode must
# demonstrate the same don't-know/refusal understanding Phase 1 ships for real
# providers, using a deterministic heuristic lexicon instead of a live model
# (docs/ARCHITECTURE.md: Mock Mode completes the whole flow with no API key, and never
