def _split_required_vs_nice(text: str, terms: list[str]) -> tuple[list[str], list[str]]:
    lower = text.lower()
    split_index = len(text)
    for marker in _NICE_TO_HAVE_MARKERS:
        idx = lower.find(marker)
        if idx != -1:
            split_index = min(split_index, idx)
    if split_index == len(text):
        return list(terms), []
    before_terms = set(h.extract_terms(text[:split_index]))
    required = [t for t in terms if t in before_terms]
    nice_to_have = [t for t in terms if t not in before_terms]
    return required, nice_to_have


def _build_job_analysis(context: dict[str, Any]) -> JobAnalysis:
    job_title = str(_get_field(context, "job_title", "")).strip() or "the role"
    experience_level = _get_field(context, "experience_level")
    experience_level = str(experience_level) if experience_level else None
    description_text = str(_get_field(context, "description_text", ""))

    terms = h.extract_terms(description_text)
    technical_terms = [t for t in terms if t not in _COMPETENCY_TERMS]
    competency_terms = [t for t in terms if t in _COMPETENCY_TERMS]

    required, nice_to_have = _split_required_vs_nice(description_text, technical_terms)
    required_labels = [_display_label(t) for t in required]
    nice_to_have_labels = [_display_label(t) for t in nice_to_have]
    technical_labels = [_display_label(t) for t in technical_terms]
    behavioral_labels = [_display_label(t) for t in competency_terms]

    sentences = h.split_sentences(description_text)
    responsibilities = _dedup([s for s in sentences if _RESPONSIBILITY_PATTERN.search(s)])[:6]

    top_topics = technical_labels[:3]
    focus = f" Focus areas include {', '.join(top_topics)}." if top_topics else ""
    level_suffix = f" ({experience_level})" if experience_level else ""
    role_summary = f"{job_title}{level_suffix} role.{focus}".strip()

    return JobAnalysis(
        job_title=job_title,
        experience_level=experience_level,
        required_skills=required_labels,
        nice_to_have_skills=nice_to_have_labels,
        responsibilities=responsibilities,
        technical_topics=technical_labels,
        behavioral_competencies=behavioral_labels,
        role_summary=role_summary,
    )


# ---- candidate_analysis ----

def _build_candidate_analysis(context: dict[str, Any]) -> CandidateAnalysis:
    cv_text = str(_get_field(context, "cv_text", ""))
    terms = h.extract_terms(cv_text)
    skills = [_display_label(t) for t in terms]
    technologies = [_display_label(t) for t in terms if t in _TECHNOLOGY_TERMS]

    sentences = h.split_sentences(cv_text)
    experience = _dedup([s for s in sentences if _EXPERIENCE_PATTERN.search(s)])[:6]
    projects = _dedup([s for s in sentences if _PROJECT_PATTERN.search(s)])[:6]
    education = _dedup([s for s in sentences if _EDUCATION_PATTERN.search(s)])[:4]

    ranked = sorted(
        ((h.specificity(s), s) for s in sentences if len(s) >= 15),
        key=lambda pair: (-pair[0], pair[1]),
    )
    important_claims = _dedup([s for _, s in ranked])[:5]
    unclear_claims = _dedup([
        s for s in important_claims
        if any(term in _VALIDATION_WORTHY_TERMS for term in h.extract_terms(s))
    ])

    return CandidateAnalysis(
        full_name=extract_explicit_candidate_name(cv_text),
        skills=skills,
        technologies=technologies,
        experience=experience,
        projects=projects,
        education=education,
        important_cv_claims=important_claims,
        relevant_experience=experience,
        unclear_claims_to_validate=unclear_claims,
    )


