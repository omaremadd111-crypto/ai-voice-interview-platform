# ---- small shared helpers ----

def _get_field(source: Any, key: str, default: Any = None) -> Any:
    if isinstance(source, BaseModel):
        return getattr(source, key, default)
    if isinstance(source, dict):
        return source.get(key, default)
    return default


def _dedup(items: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for item in items:
        if item not in seen:
            seen.add(item)
            result.append(item)
    return result


def _display_label(canonical: str) -> str:
    if canonical == "api_development":
        return "API Development"
    if canonical in {"nlp", "sql", "rag", "llm"}:
        return canonical.upper()
    return canonical.replace("_", " ").title()


def _coerce_turn(value: Any) -> InterviewTurn:
    if isinstance(value, InterviewTurn):
        return value
    return InterviewTurn.model_validate(value)


def _coerce_category(value: Any) -> EvaluationCategory:
    if isinstance(value, EvaluationCategory):
        return value
    return EvaluationCategory(value)


