_CATEGORY_ROTATION = [
    QuestionCategory.CV_PROJECT_VALIDATION,
    QuestionCategory.TECHNICAL,
    QuestionCategory.PROBLEM_SOLVING,
    QuestionCategory.BEHAVIORAL,
    QuestionCategory.CANDIDATE_BACKGROUND,
]
_POSITION_CATEGORY_ROTATION = [
    QuestionCategory.TECHNICAL,
    QuestionCategory.PROBLEM_SOLVING,
    QuestionCategory.BEHAVIORAL,
    QuestionCategory.CANDIDATE_BACKGROUND,
]
_DIFFICULTY_BY_LEVEL = {
    "Intern": "easy", "Junior": "easy", "Mid-Level": "medium",
    "Senior": "hard", "Lead": "hard", "Principal": "hard", "Executive": "hard",
}


_METRIC_PATTERN = re.compile(r"\d")
_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+|\n+")
_MAX_SEED_CHARS = 180


def _clean_claim(raw: str) -> str:
    """Reduce a raw CV excerpt to one quotable sentence.

    Extracted claims can arrive as multi-line blocks (a heading plus bullets),
    which quoted verbatim produce an unreadable question. Take the most
    informative single sentence instead, preferring one that carries a number --
    a measurable result is the most checkable thing a CV offers.
    """
    fragments = [
        fragment.strip(" \t-•*").strip()
        for fragment in _SENTENCE_SPLIT.split(raw)
        if fragment and fragment.strip(" \t-•*").strip()
    ]
    if not fragments:
        return raw.strip()[:_MAX_SEED_CHARS]
    # Ignore all-caps section headings like "EXPERIENCE" -- they are not claims.
    substantive = [f for f in fragments if not (f.isupper() and len(f.split()) <= 3)]
    candidates = substantive or fragments
    with_metric = [f for f in candidates if _METRIC_PATTERN.search(f)]
    chosen = (with_metric or candidates)[0]
    return chosen[:_MAX_SEED_CHARS].rstrip(" ,;:")


def _cv_validation_question(seed: str, _idx: int) -> tuple[str, str, list[str]]:
    claim = _clean_claim(seed)
    if _METRIC_PATTERN.search(claim):
        question = (
            f'Your CV mentions: "{claim}" What did you change to achieve that result?'
        )
        purpose = "Validate a measurable CV claim and the reasoning behind the result."
    else:
        question = (
            f'Your CV mentions: "{claim}" What was your specific role?'
        )
        purpose = "Validate a specific claim from the candidate's CV with concrete detail."
    seed = claim
    # expected_topics drives follow-up coverage checking, which is keyword-based --
    # the raw claim sentence itself is a poor fit for that (a good elaboration answer
    # naturally uses different words for the same story). Use the claim's own
    # lexicon-recognized keywords instead, falling back to the raw sentence only if
    # the claim contains no recognizable keyword at all.
    keyword_topics = [_display_label(t) for t in h.extract_terms(seed)]
    expected_topics = keyword_topics or [seed]
    return question, purpose, expected_topics


def _technical_question(seed: str, _idx: int) -> tuple[str, str, list[str]]:
    question = f"What is the most demanding thing you have built with {seed}?"
    purpose = f"Assess depth of technical knowledge in {seed}, a requirement for this role."
    return question, purpose, [seed]


def _gap_question(seed: str, _idx: int) -> tuple[str, str, list[str]]:
    """For a JD requirement the CV does not evidence.

    Deliberately neutral: a CV being silent about a skill is not evidence the
    candidate lacks it, so this asks about exposure rather than implying a
    deficiency.
    """
    question = (
        f"{seed} is important for this role, and I did not see much about it on your CV. "
        f"What exposure have you had to it?"
    )
    purpose = (
        f"Probe a job requirement not evidenced in the CV: {seed}. The CV's silence is "
        f"not evidence of absence -- this establishes the real level of exposure."
    )
    return question, purpose, [seed]


def _problem_solving_question(seed: str, _idx: int) -> tuple[str, str, list[str]]:
    focus = _clean_claim(seed)
    question = f"Tell me about a problem you solved while working on {focus}."
    purpose = "Assess problem-solving approach and reasoning process."
    seed = focus
    # Same reasoning as _cv_validation_question: seed here is often a full JD
    # responsibility sentence, which is a poor fit for keyword-based coverage checking.
    keyword_topics = [_display_label(t) for t in h.extract_terms(seed)]
    expected_topics = keyword_topics or [seed]
    return question, purpose, expected_topics


def _behavioral_question(seed: str, _idx: int) -> tuple[str, str, list[str]]:
    # Competency labels arrive title-cased for display ("Communication"); mid-sentence
    # they should read as ordinary prose, so lower the case of single-word labels.
    spoken = seed.lower() if seed.isalpha() else seed
    question = f"Tell me about a specific situation where {spoken} really mattered to the outcome."
    purpose = f"Assess the behavioral competency: {seed}."
    return question, purpose, [seed]


def _background_question(seed: str, _idx: int) -> tuple[str, str, list[str]]:
    question = f"Tell me about {seed}."
    purpose = "Understand candidate background and motivation relevant to the role."
    return question, purpose, []


_QUESTION_TEMPLATES = {
    QuestionCategory.CV_PROJECT_VALIDATION: _cv_validation_question,
    QuestionCategory.TECHNICAL: _technical_question,
    QuestionCategory.PROBLEM_SOLVING: _problem_solving_question,
    QuestionCategory.BEHAVIORAL: _behavioral_question,
    QuestionCategory.CANDIDATE_BACKGROUND: _background_question,
}


def _normalize_question(text: str) -> str:
    """Comparison key for duplicate detection: case- and punctuation-insensitive."""
    return re.sub(r"[^a-z0-9 ]+", "", text.casefold()).strip()


def _jd_gaps(job_analysis: Any, candidate_analysis: Any) -> list[str]:
    """Job requirements with no matching evidence anywhere in the candidate analysis.

    Compared on the lexicon's normalized terms so "Vector Database" on the JD
    matches "vector databases" on the CV rather than looking like a gap.
    """
    required = list(_get_field(job_analysis, "required_skills", []) or []) + list(
        _get_field(job_analysis, "technical_topics", []) or []
    )
    evidenced_text = " ".join(
        str(item)
        for field in ("skills", "technologies", "experience", "projects", "important_cv_claims")
        for item in (_get_field(candidate_analysis, field, []) or [])
    )
    evidenced_terms = set(h.extract_terms(evidenced_text))
    gaps: list[str] = []
    for requirement in required:
        requirement_terms = set(h.extract_terms(str(requirement)))
        # No recognizable terms means we cannot judge coverage -- don't guess a gap.
        if requirement_terms and not (requirement_terms & evidenced_terms):
            gaps.append(str(requirement))
    return _dedup(gaps)


def _build_interview_plan(context: dict[str, Any]) -> InterviewPlan:
    position_baseline = _get_field(context, "scope") == "position_baseline"
    if position_baseline:
        forbidden_keys = {
            "candidate_id",
            "candidate_name",
            "candidate_cv_text",
            "candidate_analysis",
            "fit_analysis",
            "candidate_interview_plan",
        }.intersection(context)
        if forbidden_keys:
            raise LLMError(
                "Position baseline planning context cannot contain candidate-specific fields."
            )

    job_title = str(_get_field(context, "job_title", "") or "the role")
    company_name = str(_get_field(context, "company_name", "") or "the company")
    experience_level = _get_field(context, "experience_level")
    num_questions = int(_get_field(context, "num_questions", 6) or 6)
    job_analysis = _get_field(context, "job_analysis", {})
    candidate_analysis = _get_field(context, "candidate_analysis", {})
    fit_analysis = _get_field(context, "fit_analysis", {})

    existing_questions = list(_get_field(context, "existing_questions", []) or [])

    n = max(num_questions, 3)
    difficulty = _DIFFICULTY_BY_LEVEL.get(str(experience_level), "medium")
    # Seeded with the position's baseline bank so generated questions never restate
    # something the candidate would already be asked.
    seen_questions: set[str] = {_normalize_question(q) for q in existing_questions}

    questions: list[InterviewQuestion] = []
    if not position_baseline:
        questions.append(InterviewQuestion(
            id="q-intro-1",
            category=QuestionCategory.INTRODUCTION,
            question="Could you briefly introduce yourself?",
            purpose="Warm-up and initial rapport; establish the candidate's framing of their own fit.",
            expected_topics=[],
            difficulty="easy",
            follow_up_allowed=False,
        ))
        seen_questions.add(_normalize_question(questions[0].question))

    # Extracted (candidate/job-specific) seeds are always preferred; each category also
    # gets a small pool of generic fallback seeds so a plan can still reach the requested
    # question count without ever repeating a seed -- and therefore a question -- within
    # the same category once its specific content runs out.
    # CV claims carrying a measurable result come first: they are the most
    # checkable thing on a CV, so they make the strongest validation questions.
    cv_claims = [] if position_baseline else _dedup([
        _clean_claim(str(claim))
        for claim in (
            list(_get_field(candidate_analysis, "unclear_claims_to_validate", []) or [])
            + list(_get_field(candidate_analysis, "important_cv_claims", []) or [])
        )
    ])
    cv_claims.sort(key=lambda claim: 0 if _METRIC_PATTERN.search(claim) else 1)

    gaps = [] if position_baseline else _jd_gaps(job_analysis, candidate_analysis)

    extracted_pools: dict[QuestionCategory, list[str]] = {
        QuestionCategory.TECHNICAL: _dedup(
            ([] if position_baseline else gaps + list(
                _get_field(fit_analysis, "missing_information", []) or []
            ))
            + list(_get_field(job_analysis, "technical_topics", []) or [])
            + list(_get_field(job_analysis, "required_skills", []) or [])
        ),
        QuestionCategory.PROBLEM_SOLVING: list(
            _get_field(job_analysis, "responsibilities", []) or []
        ),
        QuestionCategory.BEHAVIORAL: list(
            _get_field(job_analysis, "behavioral_competencies", []) or []
        ),
        QuestionCategory.CANDIDATE_BACKGROUND: [],
    }
    if not position_baseline:
        extracted_pools[QuestionCategory.CV_PROJECT_VALIDATION] = cv_claims
    gap_seeds = set(gaps)
    fallback_pools: dict[QuestionCategory, list[str]] = {
        QuestionCategory.CV_PROJECT_VALIDATION: [
            "a project you are particularly proud of",
            "a technical decision you made that you would revisit differently today",
        ],
        QuestionCategory.TECHNICAL: [
            f"a technology or tool you would expect to use as a {job_title}",
            "how you approach learning a new technology quickly",
            "how you stay current with relevant technical developments",
        ],
        QuestionCategory.PROBLEM_SOLVING: [
            "a time you had to solve a technical problem under a tight deadline",
            "a time you had to debug a difficult issue",
            "a time you had to make a technical trade-off with limited information",
        ],
        QuestionCategory.BEHAVIORAL: [
            "teamwork under pressure",
            "handling a missed deadline",
            "resolving a disagreement with a teammate",
        ],
        QuestionCategory.CANDIDATE_BACKGROUND: [
            f"your background and experience relevant to {job_title}",
            "what draws you to this particular role",
            "how your recent work connects to this position",
        ],
    }
    if position_baseline:
        fallback_pools = {
            QuestionCategory.TECHNICAL: [
                f"the core tools used by a {job_title}",
                "designing maintainable technical solutions",
                "testing and production reliability",
                "learning a role-critical technology quickly",
            ],
            QuestionCategory.PROBLEM_SOLVING: [
                "a difficult production issue",
                "a technical trade-off with limited information",
                "a delivery risk under a tight deadline",
                "an ambiguous requirement",
            ],
            QuestionCategory.BEHAVIORAL: [
                "teamwork under pressure",
                "handling a missed deadline",
                "resolving a disagreement with a teammate",
                "communicating a technical risk to stakeholders",
            ],
            QuestionCategory.CANDIDATE_BACKGROUND: [
                f"your experience relevant to the {job_title} role",
                "the work environment where you are most effective",
                "what interests you about this type of role",
                "the responsibilities you would like to deepen next",
            ],
        }
    category_rotation = (
        _POSITION_CATEGORY_ROTATION if position_baseline else _CATEGORY_ROTATION
    )
    seed_pools: dict[QuestionCategory, list[str]] = {
        cat: _dedup(extracted_pools[cat] + fallback_pools[cat]) for cat in category_rotation
    }
    used_seeds: dict[QuestionCategory, set[str]] = {cat: set() for cat in category_rotation}
    counters = {cat: 0 for cat in category_rotation}

    specific_seeds: dict[QuestionCategory, set[str]] = {
        cat: set(extracted_pools[cat]) for cat in category_rotation
    }

    def _emit(category: QuestionCategory) -> bool:
        """Add one question for this category. Returns False when it has nothing
        left to say that would not repeat an existing question."""
        for seed in seed_pools[category]:
            if seed in used_seeds[category]:
                continue
            template = (
                _gap_question
                if category is QuestionCategory.TECHNICAL and seed in gap_seeds
                else _QUESTION_TEMPLATES[category]
            )
            question_text, purpose, expected_topics = template(seed, counters[category] + 1)
            key = _normalize_question(question_text)
            if key in seen_questions:
                # Two different seeds can phrase to the same question; skip, don't
                # burn the slot on a duplicate.
                used_seeds[category].add(seed)
                continue
            used_seeds[category].add(seed)
            seen_questions.add(key)
            counters[category] += 1
            questions.append(InterviewQuestion(
                id=f"q-{category.value}-{counters[category]}",
                category=category,
                question=question_text,
                purpose=purpose,
                expected_topics=expected_topics,
                difficulty=difficulty,
                follow_up_allowed=True,
            ))
            return True
        return False

    remaining = n if position_baseline else n - 2  # candidate plans include intro/closing

    # Guarantee a balanced plan first: one technical, one problem-solving and one
    # behavioural question before anything else competes for the remaining slots,
    # so a CV rich in claims cannot crowd out whole dimensions of the interview.
    for category in (
        QuestionCategory.TECHNICAL,
        QuestionCategory.PROBLEM_SOLVING,
        QuestionCategory.BEHAVIORAL,
    ):
        if remaining <= 0:
            break
        if _emit(category):
            remaining -= 1

    # Then spend everything else on candidate-specific material before generic
    # fallbacks: a question grounded in this candidate's CV always beats a
    # template question that would suit any applicant.
    for prefer_specific in (True, False):
        rotation_pos = 0
        stalled = 0
        while remaining > 0 and stalled < len(category_rotation):
            category = category_rotation[rotation_pos % len(category_rotation)]
            rotation_pos += 1
            has_unused_specific = any(
                seed in specific_seeds[category] and seed not in used_seeds[category]
                for seed in seed_pools[category]
            )
            if prefer_specific and not has_unused_specific:
                stalled += 1
                continue
            if _emit(category):
                remaining -= 1
                stalled = 0
            else:
                stalled += 1

    if not position_baseline:
        questions.append(InterviewQuestion(
            id="q-closing-1",
            category=QuestionCategory.CLOSING,
            question=(
                f"Before we wrap up, what questions do you have about the role, the team, "
                f"or {company_name}?"
            ),
            purpose="Give the candidate an opportunity to ask questions; assess engagement.",
            expected_topics=[],
            difficulty="easy",
            follow_up_allowed=False,
        ))
    return InterviewPlan(questions=questions)


# ---- follow_up ----

_REFUSAL_MARKERS = (
    "don't know", "do not know", "dont know", "not sure", "no idea", "n/a",
    "no experience with that", "not familiar with that",
    "prefer not to answer", "skip this",
)


def _looks_like_refusal(answer: str) -> bool:
    lower = answer.strip().lower()
    if not lower:
        return True
    return any(lower == marker or (len(lower.split()) <= 6 and marker in lower) for marker in _REFUSAL_MARKERS)


def _decide_follow_up(context: dict[str, Any]) -> FollowUpDecision:
    question = _get_field(context, "question", {})
    expected_topics = list(_get_field(question, "expected_topics", []) or [])
    follow_up_allowed = bool(_get_field(question, "follow_up_allowed", True))
    latest_answer = str(_get_field(context, "latest_answer", ""))
    raw_turns_so_far = list(_get_field(context, "turns_so_far", []) or [])
    turns_so_far = [_coerce_turn(t) for t in raw_turns_so_far]

    if not follow_up_allowed:
        return FollowUpDecision(should_ask=False, reason="This question's category does not use follow-ups.")
    if _looks_like_refusal(latest_answer):
        return FollowUpDecision(
            should_ask=False,
            reason="Answer was empty or a refusal; probing further would not be productive.",
        )

    # Evaluate coverage/specificity against the full conversation for this question so
    # far, not just the latest fragment -- otherwise a topic covered in an earlier
    # answer could look "missing" again once a later, narrower answer is considered alone.
    cumulative_answer = " ".join(
        [t.answer for t in turns_so_far if t.answer and t.answer.strip()] + [latest_answer]
    ).strip()

    cov = h.coverage(cumulative_answer, expected_topics)
    spec = h.specificity(cumulative_answer)
    if cov >= 0.7 and spec >= 0.6:
        return FollowUpDecision(
            should_ask=False,
            reason=f"Answer already covers the expected topics with good specificity "
                   f"(coverage={cov:.2f}, specificity={spec:.2f}).",
        )

    missing = [t for t in expected_topics if not h.topic_mentioned(cumulative_answer, t)]
    if missing:
        target = missing[0]
        # A short topic phrase ("vector database") reads naturally inline; a long,
        # sentence-like target (e.g. a full CV claim used as its own expected_topic)
        # needs to be quoted instead, or the question comes out as a run-on artifact.
        if len(target) > 60 or target.rstrip().endswith((".", "!", "?")):
            quoted = target.rstrip(".! ")
            follow_up_question = f'You mentioned: "{quoted}" Can you go into more specific detail about that?'
        else:
            follow_up_question = f"Can you go into more detail about {target}?"
        reason = f"The answer did not clearly address expected topic: {target}."
    elif spec < 0.6:
        terms = h.extract_terms(cumulative_answer)
        if terms:
            follow_up_question = (
                f"Can you give a concrete example, including specifics like tools or "
                f"outcomes, of your work with {_display_label(terms[0])}?"
            )
        else:
            follow_up_question = "Can you give a more concrete example, with specific details or outcomes?"
        reason = f"The answer was general; low specificity score ({spec:.2f})."
    else:
        return FollowUpDecision(
            should_ask=False,
            reason="Answer is adequately specific and no expected topics are clearly missing.",
        )

    return FollowUpDecision(should_ask=True, follow_up_question=follow_up_question, reason=reason)


