def _build_fit_analysis(context: dict[str, Any]) -> FitAnalysis:
    job_analysis = _get_field(context, "job_analysis", {})
    candidate_analysis = _get_field(context, "candidate_analysis", {})

    job_required = list(_get_field(job_analysis, "required_skills", []) or [])
    job_nice = list(_get_field(job_analysis, "nice_to_have_skills", []) or [])
    job_all = _dedup(job_required + job_nice)

    candidate_skills = list(_get_field(candidate_analysis, "skills", []) or [])
    candidate_tech = list(_get_field(candidate_analysis, "technologies", []) or [])
    candidate_all = set(_dedup(candidate_skills + candidate_tech))

    strong_alignment = [s for s in job_all if s in candidate_all]
    missing_information = [s for s in job_required if s not in candidate_all]

    relevant_experience = list(
        _get_field(candidate_analysis, "relevant_experience", [])
        or _get_field(candidate_analysis, "experience", [])
        or []
    )
    unclear_claims = list(_get_field(candidate_analysis, "unclear_claims_to_validate", []) or [])
    important_claims = list(_get_field(candidate_analysis, "important_cv_claims", []) or [])
    questions_to_investigate = [f"Ask the candidate to elaborate on: {claim}" for claim in important_claims[:5]]

    return FitAnalysis(
        strong_alignment_areas=strong_alignment,
        relevant_candidate_experience=relevant_experience,
        important_job_requirements=job_required,
        skills_requiring_validation=unclear_claims,
        missing_information=missing_information,
        questions_to_investigate=questions_to_investigate,
    )


